declare @test_name varchar(200), @k varbinary(max), @d varbinary(max), @sha2_256 varbinary(64), @sha2_512 varbinary(64), @actual varbinary(64)

declare vectors cursor local fast_forward for
    select test_name, k, d, sha2_256, sha2_512 from @vectors

open vectors
fetch next from vectors into @test_name, @k, @d, @sha2_256, @sha2_512

while @@fetch_status = 0
begin
    select @actual = dbo.HMAC(@k, @d, 'SHA2_256')
    insert tests.results select * from tests.assert_equal_binary(@test_name, @sha2_256, @actual)
    select @actual = dbo.HMAC(@k, @d, 'SHA2_512'), @test_name = @test_name + ' (SHA2_512)'
    insert tests.results select * from tests.assert_equal_binary(@test_name, @sha2_512, @actual)

    fetch next from vectors into @test_name, @k, @d, @sha2_256, @sha2_512
end

close vectors
deallocate vectors
go
